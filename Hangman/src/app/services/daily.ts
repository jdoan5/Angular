/*
 * "Today's Entry": one entry a day, the same for everyone.
 *
 * Public API (consumed by the UI):
 *
 *   GameStore
 *     mode: Signal<'free' | 'daily'>
 *     startDaily(entry, category, { guesses, hintAt })   replays saved guesses in order
 *     nextWord() / backToCategories()   in a daily: back home WITHOUT a loss (the round pauses)
 *     giveUp()                          in a daily: ends it as a loss, as in free play
 *     snapshot: Signal<{ entryId, guesses, hintAt, result } | null>
 *     hintAt: Signal<number>; hintUsed is now computed from it (reads the same)
 *     free play never serves today's daily id (worked out from the schedule
 *     inside GameStore, so it never has to import this service: no cycle)
 *
 *   DailyService (this file)
 *     available, dayNumber (1-based), todayKey, today, record, state,
 *     missesUsed, alreadyCollected, streak, bestStreak, msUntilNextDay,
 *     weekStrip, records                  all signals, about TODAY (the home card)
 *     open()                              start or resume today's round (no-op once done)
 *     shareText()                         today's share text once done, else null; a computed
 *                                         signal, so it is safe to hand around unbound
 *     activeDayNo, roundShareText         the same two for the daily round ON THE BOARD (the
 *                                         play page): a round opened before midnight keeps its
 *                                         own No. and can still be shared after the date flips
 *     monthGrid(year, month0)             Monday-first weeks for the ledger
 *     refresh()                           re-read the clock and the saved ledger now
 *   Extras beyond the brief, for convenience:
 *     streaks()                           { current, best }, same values as streak/bestStreak
 *     today() is { entry, category, dayNo (0-based), key ('YYYY-MM-DD') }
 *     DAILY_EPOCH ('2026-11-02') and the DailyRecord type are re-exported here
 *
 *   Pure helpers (day keys, countdown, share text, ledger sanitiser) live in
 *   daily-math.ts; the schedule is generated by scripts/daily-schedule.mjs.
 *
 *   Clock seam: provide CLOCK (from game-store.ts) to fix the time in tests;
 *   `refresh()` re-reads it. The clock is re-read every 60 s, at local
 *   midnight, and when the tab becomes visible again.
 *
 *   Storage: 'he.daily' = Record<'YYYY-MM-DD', DailyRecord>, sanitised on load.
 *   A day's record appears with its first guess or hint (or a concession)
 *   and is rewritten after every one; a finished day is never rewritten.
 *
 *   Several tabs: every save re-reads and merges the stored ledger first, so
 *   one tab never erases another's days or rewinds a day another tab played
 *   further, and never overwrites a finished day. Other tabs' saves are also
 *   picked up on the 'storage' event, on refresh() and in open(). A daily
 *   round on this tab's board that another tab finished pauses back home;
 *   one another tab played further catches up to that tab's save.
 */

export { DAILY_EPOCH } from './daily-math';
export type { DailyRecord } from './daily-math';

export const DAILY_KEY = 'he.daily';

export type DailyState = 'none' | 'fresh' | 'in-progress' | 'done';
export type DayState = 'won' | 'lost' | 'open' | 'future';

export interface DailyToday {
  entry: WordEntry;
  category: WordCategory;
  /** 0-based day number; the player-facing "No." is this plus one. */
  dayNo: number;
  /** Local 'YYYY-MM-DD'. */
  key: string;
}

export interface WeekStripDay {
  key: string;
  /** 'Mon' … 'Sun'. */
  weekday: string;
  state: DayState;
  isToday: boolean;
}

/**
 * One ledger cell. Padding cells outside the month have `key`/`day` null and
 * state 'before' (leading) or 'future' (trailing); 'before' also marks days
 * ahead of the first daily.
 */
export interface MonthCell {
  key: string | null;
  day: number | null;
  state: DayState | 'before';
  /** Misses spent that day (also for an unfinished one); null if never played. */
  misses: number | null;
  isToday: boolean;
}

const WEEKDAY_NAMES = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
const REFRESH_MS = 60_000;

/** The entry scheduled for a day key; undefined before the epoch. */
function scheduledEntry(key: string): IndexedEntry | undefined {
  const id = scheduledIdFor(dayNumberOf(key), DAILY_SCHEDULE);
  return id === null ? undefined : findEntryById(id);
}

/** Saved rows must belong to their day's entry and be reachable in real play. */
const LEDGER_RULES: LedgerRules = {
  scheduledFor: (key) => {
    const found = scheduledEntry(key);
    return found && { id: found.entry.id, word: found.entry.word };
  },
  maxMisses: MAX_MISSES,
};

function toRecord(snapshot: RoundSnapshot): DailyRecord {
  return {
    id: snapshot.entryId,
    guesses: snapshot.guesses,
    hintAt: snapshot.hintAt,
    result: snapshot.result,
  };
}

function sameRecord(a: DailyRecord, b: DailyRecord): boolean {
  return a.id === b.id && a.guesses === b.guesses && a.hintAt === b.hintAt && a.result === b.result;
}

function sameLedger(a: Record<string, DailyRecord>, b: Record<string, DailyRecord>): boolean {
  const keys = Object.keys(a);
  return (
    keys.length === Object.keys(b).length &&
    keys.every((key) => b[key] !== undefined && sameRecord(a[key], b[key]))
  );
}

/** `next` is `saved` played on: the same guesses and maybe more, the hint where it was. */
function playsOn(saved: DailyRecord, next: DailyRecord): boolean {
  return (
    saved.id === next.id &&
    next.guesses.startsWith(saved.guesses) &&
    (saved.hintAt < 0 || saved.hintAt === next.hintAt)
  );
}

/**
 * This tab's ledger merged with the stored one. Rows only another tab has
 * are adopted, and for a day both have, the one further along wins: a
 * finished row over an unfinished one, a longer game over its own start.
 * Otherwise the stored row wins, so every tab settles on the same history.
 * Rows only this tab has are kept: storage can be read-only or unavailable.
 */
function mergeLedgers(
  mine: Record<string, DailyRecord>,
  stored: Record<string, DailyRecord>,
): Record<string, DailyRecord> {
  const merged = { ...mine };
  for (const [key, theirs] of Object.entries(stored)) {
    const own = merged[key];
    const keepOwn =
      own !== undefined &&
      ((own.result !== null && theirs.result === null) ||
        (own.result === null && theirs.result === null && playsOn(theirs, own)));
    merged[key] = keepOwn ? own : theirs;
  }
  return merged;
}

function misses(record: DailyRecord): number {
  return missesFor(record.guesses, findEntryById(record.id)?.entry.word ?? '', record.hintAt);
}

@Injectable({ providedIn: 'root' })
export class DailyService {
  private readonly store = inject(GameStore);
  private readonly storage = inject(StorageService);
  private readonly clock = inject(CLOCK);
  private readonly document = inject(DOCUMENT);

  /** The clock as of the last refresh; every time-derived signal hangs off it. */
  private readonly now = signal(this.clock().getTime());
  private readonly ledger = signal<Record<string, DailyRecord>>(this.load());
  /**
   * Day key of the daily round open() last started. A round opened just
   * before midnight keeps saving to the day it belongs to after the date flips.
   */
  private readonly activeKey = signal<string | null>(null);
  /** That day, while its round is the one on the board (null outside a daily). */
  private readonly roundKey = computed(() =>
    this.store.mode() === 'daily' ? this.activeKey() : null,
  );

  readonly records = this.ledger.asReadonly();
  readonly todayKey = computed(() => localDayKey(new Date(this.now())));
  private readonly dayNo = computed(() => dayNumberOf(this.todayKey()));

  readonly today = computed<DailyToday | null>(() => {
    const key = this.todayKey();
    const found = scheduledEntry(key);
    return found
      ? { entry: found.entry, category: found.category, dayNo: this.dayNo(), key }
      : null;
  });
  /** False before the first daily. */
  readonly available = computed(() => this.today() !== null);
  /** The player-facing "No.", 1-based (0 while unavailable). */
  readonly dayNumber = computed(() => (this.available() ? this.dayNo() + 1 : 0));

  readonly record = computed<DailyRecord | null>(() => {
    const today = this.today();
    if (!today) return null;
    const record = this.ledger()[today.key];
    // A row saved for some other entry (the schedule moved under it) doesn't count.
    return record && record.id === today.entry.id ? record : null;
  });

  readonly state = computed<DailyState>(() => {
    if (!this.today()) return 'none';
    const record = this.record();
    return !record ? 'fresh' : record.result ? 'done' : 'in-progress';
  });

  readonly missesUsed = computed(() => {
    const record = this.record();
    return record ? misses(record) : 0;
  });

  /** Today's entry was in the encyclopedia before today: a warm-up, not a discovery. */
  readonly alreadyCollected = computed(() => {
    const today = this.today();
    const at = today ? this.store.collection()[today.entry.id] : undefined;
    if (!today || at === undefined) return false;
    // Winning today's daily collects it as well; that alone doesn't make it a warm-up.
    return this.record()?.result !== 'won' || localDayKey(new Date(at)) < today.key;
  });

  /** Derived from consecutive won days, never stored. */
  readonly streaks = computed(() => dailyStreaks(this.ledger(), this.todayKey()));
  readonly streak = computed(() => this.streaks().current);
  readonly bestStreak = computed(() => this.streaks().best);

  readonly msUntilNextDay = computed(() => msUntilMidnight(new Date(this.now())));

  /** Monday to Sunday of the current week, for the fact card. */
  readonly weekStrip = computed<WeekStripDay[]>(() => {
    if (!this.available()) return [];
    const todayKey = this.todayKey();
    const ledger = this.ledger();
    const monday = addDays(todayKey, -weekdayIndex(todayKey));
    return WEEKDAY_NAMES.map((weekday, i) => {
      const key = addDays(monday, i);
      return { key, weekday, state: dayState(key, todayKey, ledger), isToday: key === todayKey };
    });
  });

  /** Today's spoiler-free result, once today is finished (else null). For the home card. */
  readonly shareText = computed<string | null>(() => {
    const today = this.today();
    return today ? this.shareFor(today.key) : null;
  });

  /**
   * The player-facing "No." of the daily round on the board, for the play
   * page. A round opened before midnight keeps its own number after the date
   * flips. Outside a daily round, today's number.
   */
  readonly activeDayNo = computed(() => {
    const key = this.roundKey();
    return key ? dayNumberOf(key) + 1 : this.dayNumber();
  });

  /**
   * The share text of the daily round on the board once it's finished (else
   * null), for the fact card. Unlike shareText(), it follows the round's own
   * day, so a daily finished just after midnight can still be shared.
   */
  readonly roundShareText = computed<string | null>(() => {
    const key = this.roundKey();
    return key ? this.shareFor(key) : null;
  });

  constructor() {
    // Save after every guess and hint. The ledger is read untracked: this
    // effect writes it, and only a change to the round should re-run it.
    effect(() => {
      const snapshot = this.store.snapshot();
      const daily = this.store.mode() === 'daily';
      if (daily && snapshot) untracked(() => this.persist(snapshot));
    });

    // Keep the countdown fresh, and flip the day at local midnight on the dot
    // (the interval alone could leave yesterday's card up for a minute).
    const interval = setInterval(() => this.refresh(), REFRESH_MS);
    let midnight: ReturnType<typeof setTimeout> | undefined;
    const armMidnight = () => {
      clearTimeout(midnight);
      // A beat past midnight, so the re-read clock is safely on the new day.
      midnight = setTimeout(
        () => {
          this.refresh();
          armMidnight();
        },
        msUntilMidnight(this.clock()) + 250,
      );
    };
    armMidnight();
    // Timers stall while a laptop sleeps; catch up as soon as the tab is seen again.
    const onVisible = () => {
      if (this.document.visibilityState !== 'visible') return;
      this.refresh();
      armMidnight();
    };
    this.document.addEventListener('visibilitychange', onVisible);
    // Another tab saved (null: it cleared storage outright). Not fired for this tab's own writes.
    const view = this.document.defaultView;
    const onStorage = (event: StorageEvent) => {
      if (event.key === DAILY_KEY || event.key === null) this.syncFromStorage();
    };
    view?.addEventListener('storage', onStorage);
    inject(DestroyRef).onDestroy(() => {
      clearInterval(interval);
      clearTimeout(midnight);
      this.document.removeEventListener('visibilitychange', onVisible);
      view?.removeEventListener('storage', onStorage);
    });
  }

  /**
   * Re-read the clock and the saved ledger (the timers and the tab becoming
   * visible do this; tests with a fixed CLOCK call it).
   */
  refresh(): void {
    this.now.set(this.clock().getTime());
    this.syncFromStorage();
  }

  /** Start today's round, or resume it exactly where it was left. A finished day stays finished. */
  open(): void {
    // Another tab may have played or finished today since this one last looked.
    this.syncFromStorage();
    const today = this.today();
    if (!today) return;
    const record = this.record();
    if (record?.result) return;
    const store = this.store;
    if (store.mode() === 'daily' && store.phase() === 'playing' && this.activeKey() === today.key)
      return;
    // Leaving a free-play round for the daily is a walk-away like any other.
    if (store.mode() === 'free' && store.phase() === 'playing') store.backToCategories();

    this.activeKey.set(today.key);
    store.startDaily(today.entry, today.category, {
      guesses: record?.guesses ?? '',
      hintAt: record?.hintAt ?? -1,
    });
  }

  /**
   * One month of the ledger as Monday-first weeks. Reads signals, so calling
   * it from a template or computed() tracks the ledger and the date.
   */
  monthGrid(year: number, month0: number): MonthCell[][] {
    const todayKey = this.todayKey();
    const ledger = this.ledger();
    const first = dayKeyOf(year, month0, 1);
    const length = Number(dayKeyOf(year, month0 + 1, 0).slice(8));

    const pad = (state: 'before' | 'future'): MonthCell => ({
      key: null,
      day: null,
      state,
      misses: null,
      isToday: false,
    });
    const cells: MonthCell[] = Array.from({ length: weekdayIndex(first) }, () => pad('before'));
    for (let day = 1; day <= length; day++) {
      const key = addDays(first, day - 1);
      const record = ledger[key];
      const before = key < DAILY_EPOCH;
      const state = before ? 'before' : dayState(key, todayKey, ledger);
      const played = record && !before && key <= todayKey;
      cells.push({
        key,
        day,
        state,
        misses: played ? misses(record) : null,
        isToday: key === todayKey,
      });
    }
    while (cells.length % 7) cells.push(pad('future'));

    const weeks: MonthCell[][] = [];
    for (let i = 0; i < cells.length; i += 7) weeks.push(cells.slice(i, i + 7));
    return weeks;
  }

  /** The stored ledger, sanitised against the schedule. */
  private load(): Record<string, DailyRecord> {
    return sanitizeLedger(this.storage.get<unknown>(DAILY_KEY, {}), LEDGER_RULES);
  }

  /** Merge in what other tabs saved, then square the round on the board with it. */
  private syncFromStorage(): void {
    const merged = mergeLedgers(this.ledger(), this.load());
    if (!sameLedger(merged, this.ledger())) this.ledger.set(merged);
    this.reconcile();
  }

  /**
   * A daily round still in play here, whose day another tab has finished,
   * pauses back home: a finished day is final, and the home card shows it.
   * One another tab played further catches up to that save, which is the
   * real attempt. A round this tab is ahead on is left alone (its save is
   * on the way).
   */
  private reconcile(): void {
    const key = this.activeKey();
    const store = this.store;
    const snapshot = store.snapshot();
    if (!key || store.mode() !== 'daily' || store.phase() !== 'playing' || !snapshot) return;
    const saved = this.ledger()[key];
    if (!saved || saved.id !== snapshot.entryId) return;
    if (saved.result) {
      store.backToCategories();
    } else if (!playsOn(saved, toRecord(snapshot))) {
      const found = scheduledEntry(key)!;
      store.startDaily(found.entry, found.category, saved);
    }
  }

  /** The share text of any finished day, or null. */
  private shareFor(key: string): string | null {
    const ledger = this.ledger();
    const record = ledger[key];
    const found = scheduledEntry(key);
    if (!record?.result || !found || record.id !== found.entry.id) return null;
    return buildShareText({
      dailyNo: dayNumberOf(key) + 1,
      icon: found.category.icon,
      word: found.entry.word,
      guesses: record.guesses,
      hintAt: record.hintAt,
      result: record.result,
      maxMisses: MAX_MISSES,
      // The streak as of that day, which counts the day itself.
      streak: dailyStreaks(ledger, key).current,
    });
  }

  private persist(snapshot: RoundSnapshot): void {
    const key = this.activeKey();
    // Only the round open() started, and only the entry scheduled for its day.
    if (!key || snapshot.entryId !== scheduledEntry(key)?.entry.id) return;
    // Re-read first: another tab may have saved since, and its days must survive this write.
    const ledger = mergeLedgers(this.ledger(), this.load());
    if (!sameLedger(ledger, this.ledger())) this.ledger.set(ledger);
    const saved = ledger[key];
    const next = toRecord(snapshot);

    if (saved?.result) {
      // A finished day is final, whichever tab finished it.
      this.reconcile();
      return;
    }
    // Opened but untouched isn't an attempt yet; the first guess or hint makes it one.
    if (!saved && !next.guesses && next.hintAt < 0 && !next.result) return;
    if (saved && sameRecord(saved, next)) return; // e.g. the replay on resume
    if (saved && !playsOn(saved, next)) {
      // Another tab got further with this day: catch up rather than rewind it.
      this.reconcile();
      return;
    }
    const updated = { ...ledger, [key]: next };
    this.ledger.set(updated);
    this.storage.set(DAILY_KEY, updated);
  }
}

function dayState(key: string, todayKey: string, ledger: Record<string, DailyRecord>): DayState {
  if (key > todayKey) return 'future';
  const result = ledger[key]?.result;
  return result === 'won' || result === 'lost' ? result : 'open';
}
